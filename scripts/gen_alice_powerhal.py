#!/usr/bin/env python3
"""Embed the short bootstrap and expose a CI-built, public-source ELF read-only."""
from pathlib import Path
import argparse
import base64
import json

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--elf', type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
payload = base64.b64encode((root/'alice/powerhal/boot.sh').read_bytes()).decode()
state = '/data/adb/alice-powerhal'
command = (f'umask 077; mkdir -p {state} || exit 1; chmod 0700 {state} || exit 1; '
           f'printf %s {payload} | /system/bin/base64 -d > {state}/boot.sh.tmp && '
           f'chmod 0600 {state}/boot.sh.tmp && mv {state}/boot.sh.tmp {state}/boot.sh && '
           f'exec /system/bin/sh {state}/boot.sh')
rc = ('\n# ALICE_POWERHAL_R12\non post-fs-data\n'
      f'    exec u:r:ksu:s0 root root -- /system/bin/timeout 8 /system/bin/sh -c "{command}"\n\n'
      f'service alice-powerhal-guard /system/bin/timeout 20 /system/bin/sh {state}/boot.sh guard\n'
      '    user root\n    group root\n    seclabel u:r:ksu:s0\n    disabled\n    oneshot\n\n'
      'on property:init.svc.vendor.samsung.power-default=running\n    start alice-powerhal-guard\n\n')
lines = []
for line in rc.splitlines(keepends=True):
    for i in range(0, len(line), 100):
        lines.append(json.dumps(line[i:i+100]).replace('u:r:ksu:s0', 'u:r:" KERNEL_SU_DOMAIN ":s0'))
continuation = ' ' + chr(92) + '\n'
header = '/* Generated by scripts/gen_alice_powerhal.py; do not edit. */\n'
header += '#define ALICE_POWERHAL_RC' + continuation
header += continuation.join('    ' + line for line in lines) + '\n'
dest = root/'drivers/kernelsu/runtime/alice_powerhal_payload.h'
if args.check:
    assert dest.read_text() == header, 'stale Power HAL bootstrap'
else:
    dest.write_text(header)
if args.elf:
    data = args.elf.read_bytes()
    assert data[:4] == b'\x7fELF' and data[4] == 2 and int.from_bytes(data[18:20], 'little') == 183
    assert len(data) < 1024 * 1024, 'unexpected service size'
    blob = '/* Generated from the public-source CI ELF; not committed. */\n'
    blob += 'static const unsigned char alice_powerhal_elf[] = {\n'
    blob += '\n'.join(','.join('0x%02x' % b for b in data[i:i+20]) + ',' for i in range(0, len(data), 20))
    blob += '\n};\n'
    (root/'kernel/power/alice_powerhal_blob.h').write_text(blob)
    print('Embedded AArch64 Power HAL ELF:', len(data), 'bytes')
