#!/usr/bin/env python3
"""Embed finite early CPU compatibility actions in the existing KSU RC hook."""
from pathlib import Path
import base64
import json
import sys

root = Path(__file__).resolve().parent.parent
script = (root/'alice/cpu-compat/boot.sh').read_bytes()
payload = base64.b64encode(script).decode('ascii')
state = '/data/adb/alice-cpu-compat'
command = (
    f'umask 077; mkdir -p {state} || exit 1; chmod 0700 {state} || exit 1; '
    f'printf %s {payload} | /system/bin/base64 -d > {state}/boot.sh.tmp && '
    f'chmod 0600 {state}/boot.sh.tmp && mv {state}/boot.sh.tmp {state}/boot.sh && '
    f'exec /system/bin/sh {state}/boot.sh apply'
)
rc = (
    '\n# ALICE_CPU_COMPAT_R14\n'
    'on post-fs-data\n'
    f'    exec u:r:ksu:s0 root root -- /system/bin/timeout 8 /system/bin/sh -c "{command}"\n'
    '\non property:init.svc.surfaceflinger=running\n'
    f'    exec u:r:ksu:s0 root root -- /system/bin/timeout 5 /system/bin/sh {state}/boot.sh join\n'
    '\non property:sys.boot_completed=1\n'
    f'    exec u:r:ksu:s0 root root -- /system/bin/timeout 8 /system/bin/sh {state}/boot.sh apply\n\n'
)
lines=[]
for line in rc.splitlines(keepends=True):
    # Keep the existing KSU domain macro rather than introducing a new domain.
    for n in range(0,len(line),100):
        lines.append(json.dumps(line[n:n+100]).replace('u:r:ksu:s0','u:r:" KERNEL_SU_DOMAIN ":s0'))
continuation=' '+chr(92)+'\n'
header='/* Generated by scripts/gen_alice_cpu_compat.py; do not edit. */\n'
header+='#define ALICE_CPU_COMPAT_RC'+continuation
header+=continuation.join('    '+line for line in lines)+'\n'
dest=root/'drivers/kernelsu/runtime/alice_cpu_compat_payload.h'
if '--check' in sys.argv:
    assert dest.read_text()==header, 'Embedded CPU compatibility payload is stale'
else:
    dest.write_text(header)
