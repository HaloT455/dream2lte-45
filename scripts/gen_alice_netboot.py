#!/usr/bin/env python3
"""Embed the audited startup script into existing KernelSU init RC injection."""
from pathlib import Path
import base64
import json
import sys

root = Path(__file__).resolve().parent.parent
script = (root/'alice/netboot/boot.sh').read_bytes()
payload = base64.b64encode(script).decode('ascii')
state = '/data/adb/alice-netboot'
command = (
    f'umask 077; mkdir -p {state} || exit 1; chmod 0700 {state} || exit 1; '
    f'if [ -e {state}/disable ]; then exit 0; fi; '
    f'printf %s {payload} | /system/bin/base64 -d > {state}/boot.sh.tmp && '
    f'chmod 0600 {state}/boot.sh.tmp && mv {state}/boot.sh.tmp {state}/boot.sh && '
    f'exec /system/bin/sh {state}/boot.sh'
)
rc = (
    '\n# ALICE_NETBOOT_R1\n'
    f'service alice-netboot /system/bin/sh -c "{command}"\n'
    '    class late_start\n'
    '    user root\n'
    '    group root system inet shell\n'
    '    seclabel u:r:ksu:s0\n'
    '    disabled\n'
    '    oneshot\n'
    '\non property:init.svc.zygote=running\n'
    '    start alice-netboot\n'
    '\non property:sys.boot_completed=1\n'
    '    start alice-netboot\n\n'
)
lines = []
for line in rc.splitlines(keepends=True):
    if 'u:r:ksu:s0' in line:
        lines.append(json.dumps(line).replace('u:r:ksu:s0', 'u:r:" KERNEL_SU_DOMAIN ":s0'))
    else:
        lines.extend(json.dumps(line[n:n+100]) for n in range(0, len(line), 100))
header = '/* Generated by scripts/gen_alice_netboot.py; do not edit. */\n'
continuation = ' ' + chr(92) + '\n'
header += '#define ALICE_NETBOOT_RC' + continuation
header += continuation.join('    ' + line for line in lines) + '\n'
dest = root/'drivers/kernelsu/runtime/alice_netboot_payload.h'
if '--check' in sys.argv:
    assert dest.read_text() == header, 'Embedded network startup payload is stale'
else:
    dest.write_text(header)
