#!/system/bin/sh
# ALICE V12R62 user-initiated local inference. No writes outside own temp dir.
set -eu
MOD=/data/adb/modules/alice_ai_offline
MODEL="$MOD/Qwen3-0.6B-Q4_K_M.gguf"
BIN="$MOD/llama-cli"
[ -f "$MODEL" ] || { echo 'ALICE_NO_MODEL' >&2; exit 11; }
[ -x "$BIN" ] || { echo 'ALICE_NO_LLAMA_CLI' >&2; exit 12; }
umask 077
DIR="$MOD/tmp"
mkdir -p "$DIR"
P="$DIR/prompt.$$"
# Fixed-size input: cap prompt to prevent untrusted user data filling storage.
head -c 8192 > "$P"
trap 'rm -f "$P"' EXIT HUP INT TERM
# Model stays unloaded between requests, CPU threads capped for S8+.
# Input already uses the Qwen3 conversation template, generated by the APK.
exec 3<&0
"$BIN" -m "$MODEL" -t 3 -c 1024 -n 128 \
  --no-display-prompt --no-show-timings --simple-io \
  -f "$P"
